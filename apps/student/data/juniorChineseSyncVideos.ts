export function getJuniorChineseSyncTopics(grade: string, term: string, version = '人教版'): JuniorChineseSyncTopic[] {
  return JUNIOR_CHINESE_SYNC_TOPICS.filter(
    (topic) => topic.grade === grade && topic.term === term && topic.version === version,
  );
}

export function getJuniorChineseTextbookVersions(grade: string, term: string): string[] {
  return [...new Set(
    JUNIOR_CHINESE_SYNC_TOPICS
      .filter((topic) => topic.grade === grade && topic.term === term)
      .map((topic) => topic.version),
  )];
}

export function extractChineseSubWork(title: string, section: string): string {
  const lessonName = section.replace(/^\d+\s*/, '');
  const idx = title.indexOf(lessonName);
  if (idx < 0) return '';
  const rest = title.slice(idx + lessonName.length).replace(/^[-_—－\s]+/, '');
  const parts = rest.split('_').filter(Boolean);
  return parts.length >= 2 ? parts[0] : '';
}

export function splitChineseLessonTopics<T extends { section: string; videos: Array<{ title: string }> }>(lesson: T): T[] {
  const groups = new Map<string, T['videos']>();
  lesson.videos.forEach((video) => {
    const work = extractChineseSubWork(video.title, lesson.section) || lesson.section;
    const list = groups.get(work) ?? [];
    list.push(video);
    groups.set(work, list);
  });
  if (groups.size <= 1) return [lesson];
  return [...groups.entries()].map(([section, videos]) => ({ ...lesson, section, videos }));
}
