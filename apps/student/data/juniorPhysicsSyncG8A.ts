export interface PhysicsVideo {
  id: string;
  title: string;
}

export interface PhysicsCategory {
  id: string;
  title: string;
  videos: PhysicsVideo[];
}

export interface PhysicsSection {
  id: string;
  title: string;
  categories: PhysicsCategory[];
}

export interface PhysicsChapter {
  id: string;
  title: string;
  sections: PhysicsSection[];
}

const CATEGORY_ORDER = ['知识点', '题型', '易错', '中考链接'] as const;
type CategoryTitle = (typeof CATEGORY_ORDER)[number];

const videos = (id: string, titles: string[]): PhysicsVideo[] =>
  titles.map((title, index) => ({ id: `${id}-v${index + 1}`, title }));

const categories = (id: string, groups: Partial<Record<CategoryTitle, string[]>>): PhysicsCategory[] =>
  CATEGORY_ORDER
    .filter((title) => (groups[title]?.length ?? 0) > 0)
    .map((title) => ({
      id: `${id}-${title}`,
      title,
      videos: videos(`${id}-${title}`, groups[title] ?? []),
    }));

const section = (id: string, title: string, groups: Partial<Record<CategoryTitle, string[]>>): PhysicsSection => ({
  id,
  title,
  categories: categories(id, groups),
});

