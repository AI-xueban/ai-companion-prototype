import assert from 'node:assert/strict';
import { build } from 'esbuild';

const result = await build({ entryPoints: ['components/Teacher/data/borrowingControl.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { borrowingListSummary, deleteGroupedBorrowingRule, groupBorrowingRules, initialBorrowingState, setTemporaryBorrowing, classTemporarilyDenied, saveClassBorrowingRule, saveGroupedBorrowingRule, borrowingResult } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const friday = new Date('2026-10-23T08:30:00+08:00');
const saturday = new Date('2026-10-24T08:30:00+08:00');
const student = { id: 'stable-student-id', classId: 'c1' };
const weekly = { id: 'weekly', mode: 'weekly', weekdays: [4], startDate: '', endDate: '', deny: false, periods: [{ start: '08:00', end: '10:00' }] };
const dates = { ...weekly, id: 'date', mode: 'dates', weekdays: [], startDate: '2026-10-24', endDate: '2026-10-24' };
let state = initialBorrowingState();
assert.equal(borrowingResult(state, student, friday), '当前可借用');
state = saveClassBorrowingRule(state, ['c1','c2'], weekly);
assert.equal(borrowingResult(state, student, friday), '当前可借用');
assert.equal(borrowingResult(state, student, saturday), '当前不在借用时段');
state = saveClassBorrowingRule(state, ['c1'], dates);
assert.equal(borrowingResult(state, student, saturday), '当前可借用');
assert.equal(borrowingResult(state, { ...student, classId: 'c2' }, saturday), '当前不在借用时段');
state = saveClassBorrowingRule(state, ['c1'], { ...dates, deny: true }, dates.id);
assert.equal(borrowingResult(state, student, saturday), '指定日期禁止借用');
state = { ...state, studentBans: { [student.id]: true } };
state = setTemporaryBorrowing(state, ['c1','c2'], true, true);
assert.equal(borrowingResult(state, student, friday), '学校临时禁止借用');
state = setTemporaryBorrowing(state, ['c1'], false);
assert.equal(state.schoolTemporaryActive, true);
assert.equal(classTemporarilyDenied(state, 'c1'), false);
assert.equal(classTemporarilyDenied(state, 'c2'), true);
assert.equal(classTemporarilyDenied(state, 'new-class'), true);
assert.equal(borrowingResult(state, student, friday), '班主任已禁止借用');
state = saveClassBorrowingRule(state, ['c1'], { ...weekly, periods: [{ start: '09:00', end: '10:00' }] }, weekly.id);
state = setTemporaryBorrowing(state, ['c1'], true);
state = setTemporaryBorrowing(state, ['c1','c2'], false, true);
assert.deepEqual(state.temporaryClasses, {});
assert.equal(classTemporarilyDenied(state, 'c2'), false);
assert.equal(state.studentBans[student.id], true);
assert.equal(borrowingResult(state, { ...student, classId:'c2' }, friday), '班主任已禁止借用', '学生转班保留禁借');
assert.equal(borrowingResult(state, { id:'new-student', classId:'c1' }, friday), '当前不在借用时段', '解除执行最新时间，不回滚');
assert.equal(borrowingResult(state, { id:'new-student', classId:'c2' }, friday), '当前可借用', '新增学生继承班级时间，不继承历史学生禁借');
state = setTemporaryBorrowing(state, ['c2'], true);
state = setTemporaryBorrowing(state, ['c1'], false);
assert.equal(classTemporarilyDenied(state, 'c2'), true, '局部解除不影响其他班级');
const split = saveClassBorrowingRule(saveClassBorrowingRule(initialBorrowingState(), ['c1'], { ...weekly, weekdays:[0,1,2,3,4] }), ['c1'], { ...weekly, id:'replace', weekdays:[2] });
assert.deepEqual(split.classRules.c1[0].weekdays,[0,1,3,4]);
const range = saveClassBorrowingRule(saveClassBorrowingRule(initialBorrowingState(), ['c1'], { ...dates, startDate:'2026-10-23', endDate:'2026-10-27' }), ['c1'], { ...dates, id:'middle', startDate:'2026-10-25', endDate:'2026-10-25', deny:true });
assert.deepEqual(range.classRules.c1.map(rule=>[rule.startDate,rule.endDate]),[['2026-10-23','2026-10-24'],['2026-10-26','2026-10-27'],['2026-10-25','2026-10-25']]);
console.log('Borrowing control: all assertions passed (日期优先、局部解除、最新规则、转班与新增学生、范围覆盖).');

const identical = { ...state, classRules: { c1: [weekly, {...weekly, id:'sat', weekdays:[5]}], c2: [{...weekly, id:'other'}, {...weekly, id:'other-sat', weekdays:[5]}] } };
assert.equal(borrowingListSummary(identical,['c1','c2'],'weekly').note,'—');
assert.equal(borrowingListSummary(identical,['c1'],'weekly').rules.length,2);
assert.equal(borrowingListSummary(identical,['c1','empty'],'weekly').note,'部分班级未设置规则');
assert.equal(borrowingListSummary(identical,['empty'],'weekly').note,'未设置规则');
assert.equal(borrowingListSummary({...identical,classRules:{...identical.classRules,c2:[weekly]}},['c1','c2'],'weekly').note,'各班规则不同');
const sameContent = { ...initialBorrowingState(), classRules: { c1: [weekly], c2: [{ ...weekly, id: 'another-id' }], c3: [{ ...weekly, id: 'third-id', periods: [{ start: '09:00', end: '11:00' }] }] } };
const grouped = groupBorrowingRules(sameContent, ['c1', 'c2', 'c3'], 'weekly');
assert.equal(grouped.length, 2, '相同内容的不同 ID 合并展示');
assert.deepEqual(grouped[0].entries, [{ classId: 'c1', ruleId: 'weekly' }, { classId: 'c2', ruleId: 'another-id' }]);
const editedGroup = saveGroupedBorrowingRule(sameContent, grouped[0].entries, { ...weekly, periods: [{ start: '10:00', end: '12:00' }] });
assert.equal(editedGroup.classRules.c1[0].id, 'weekly');
assert.equal(editedGroup.classRules.c2[0].id, 'another-id', '编辑后保留各班原 ID');
assert.equal(editedGroup.classRules.c3[0].periods[0].start, '09:00', '其他配置不受影响');
const deletedGroup = deleteGroupedBorrowingRule(sameContent, grouped[0].entries);
assert.equal(deletedGroup.classRules.c1.length, 0);
assert.equal(deletedGroup.classRules.c2.length, 0);
assert.equal(deletedGroup.classRules.c3.length, 1, '删除只作用于所展示的规则组');
const currentDate = { ...dates, startDate: '2026-10-26', endDate: '2026-10-28' };
const expiredDate = { ...dates, id: 'expired', startDate: '2026-10-01', endDate: '2026-10-02' };
const mixedDates = { ...identical, classRules: { c1: [currentDate, expiredDate], c2: [{ ...currentDate, id: 'other-current' }] } };
assert.equal(borrowingListSummary(mixedDates, ['c1', 'c2'], 'dates').note, '各班规则不同');
assert.equal(borrowingListSummary(mixedDates, ['c1', 'c2'], 'dates', rule => rule.endDate >= '2026-10-27').note, '—', '已失效日期不造成差异');
const policyResult = await build({ entryPoints: ['components/Teacher/data/hierarchicalDeviceControl.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { validateSchedule } = await import(`data:text/javascript;base64,${Buffer.from(policyResult.outputFiles[0].text).toString('base64')}`);
const today = new Date('2026-10-27T12:00:00+08:00');
assert.equal(validateSchedule(currentDate, today), '生效日期只能选择当天及之后');
assert.equal(validateSchedule(currentDate, today, currentDate.startDate), '', '已生效规则可保留历史开始日期并调整结束日期');
assert.equal(validateSchedule({ ...currentDate, endDate: '2026-10-26' }, today, currentDate.startDate), '结束日期不能早于今天');
console.log('PASS list configuration content and missing-class explanations');

let defaults = initialBorrowingState();
assert.equal(borrowingResult(defaults,student,friday),'当前可借用');
defaults = saveClassBorrowingRule(defaults,['c1'],{...dates,deny:true});
assert.equal(borrowingResult(defaults,student,friday),'当前可借用','未来日期规则不限制今天');
assert.equal(borrowingResult(defaults,student,saturday),'指定日期禁止借用');
assert.equal(borrowingResult(defaults,student,new Date('2026-10-25T08:30:00+08:00')),'当前可借用','日期到期且无每周规则恢复默认可借');
assert.equal(borrowingResult(setTemporaryBorrowing(initialBorrowingState(),['c1'],true),student,friday),'学校临时禁止借用');
assert.equal(borrowingResult({...initialBorrowingState(),studentBans:{[student.id]:true}},student,friday),'班主任已禁止借用');
assert.equal(borrowingResult(saveClassBorrowingRule(initialBorrowingState(),['c1'],weekly),student,new Date('2026-10-23T11:00:00+08:00')),'当前不在借用时段');
console.log('PASS default allow, date lifecycle, weekly gaps and ban precedence');
