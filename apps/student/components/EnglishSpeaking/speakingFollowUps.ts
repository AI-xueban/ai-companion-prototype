export function buildSpeakingPrompts(en: string, opening: SpeakingPrompt, followUp?: SpeakingPrompt): SpeakingPrompt[] {
  const group = Object.keys(sceneGroups).find(key => sceneGroups[key].includes(en));
  if (!group) throw new Error('Missing speaking conversation: ' + en);
  const steps = conversations[group];
  return [
    opening,
    followUp ?? steps[0],
    ...steps.slice(1),
    ['Could you sum up the main idea of our chat in one sentence?', '你能用一句话总结刚才聊天的主要内容吗？', opening[2], opening[3]],
    ['Thanks for chatting with me! What would you like to say before we finish?', '谢谢你和我聊天！结束前你还想说什么？', 'Thank you for chatting with me. See you next time!', '谢谢你陪我聊天，下次见！'],
  ];
}
