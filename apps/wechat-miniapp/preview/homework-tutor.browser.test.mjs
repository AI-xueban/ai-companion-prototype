import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {chromium} from 'playwright';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const output=process.env.TUTOR_REPORT_DIR||fileURLToPath(new URL('../../../output/homework-tutor/',import.meta.url));mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const shot=async name=>page.locator('.device').screenshot({path:resolve(output,name+'.png')});
try{
  await page.goto((process.env.DEMO_BASE_URL||'http://127.0.0.1:4177/')+'?review=1&page=parent');
  await page.waitForFunction(()=>window.parentPrototype&&window.homeworkTutorUI&&window.homeworkTutor);
  await page.evaluate(()=>{parentPrototype.scenario('returning');parentPrototype.tab('homework');homeworkPrototype.openParent('grading-demo-v1');homeworkPrototype.openParentGrade();});
  await page.getByRole('button',{name:'1对1讲题',exact:true}).click();
  assert.equal(await page.locator('.ht-root').count(),1);assert.equal(await page.getByText('进入 1 对 1 引导',{exact:true}).count(),0);
  await page.getByRole('button',{name:'暂停',exact:true}).click();await shot('01-讲题板书与字幕');
  await page.getByRole('button',{name:'继续播放',exact:true}).click();
  for(let i=0;i<8&&await page.locator('.ht-options').count()===0;i++)await page.getByRole('button',{name:'下一段',exact:true}).click();
  assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'waiting');
  const before=await page.evaluate(()=>homeworkTutorUI.inspect());
  await page.waitForTimeout(200);assert.equal((await page.evaluate(()=>homeworkTutorUI.inspect())).cursor,before.cursor);
  await shot('02-暂停提问');
  assert.equal(await page.locator('#ht-draft').count(),0,'The answer editor is collapsed until requested');
  await page.getByRole('button',{name:'切换文字输入',exact:true}).click();
  await shot('02b-文字输入');
  await page.locator('#ht-draft').fill('我不确定');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'waiting','Typing at a checkpoint submits an answer rather than opening an aside');
  const options=await page.locator('.ht-options>button').allTextContents();assert.ok(options.length>=2);
  await page.locator('.ht-options>button').first().click();
  assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'feedback');
  assert.equal(await page.locator('.ht-sheet').count(),1,'Feedback stays in the bottom sheet');
  await page.getByRole('button',{name:'继续讲解',exact:true}).click();
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  await page.getByRole('button',{name:'有疑问，随时问我',exact:true}).click();await shot('03-局部补讲');
  await page.getByRole('button',{name:'切换文字输入',exact:true}).click();
  await page.locator('#ht-draft').fill('为什么要先求一份？');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'aside');
  await page.getByRole('button',{name:'返回暂停位置',exact:true}).click();assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'paused');
  await page.evaluate(()=>homeworkPrototype.closeHomeworkLearning());assert.equal(await page.locator('.ht-root').count(),0);
  await page.getByRole('button',{name:'1对1讲题',exact:true}).click();assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'resume');await shot('04-继续上次讲解');
  await page.getByRole('button',{name:'继续上次',exact:true}).click();
  await page.getByRole('button',{name:'查看原题',exact:true}).click();assert.equal(await page.locator('.ht-modal').count(),1);
  await page.getByRole('button',{name:'返回讲题',exact:true}).click();assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'paused');
  const saved=await page.evaluate(()=>JSON.stringify(homeworkTutorUI.inspect().evidence));
  await page.evaluate(()=>{homeworkTutorUI.restart();homeworkTutorUI.direct();});
  for(let i=0;i<15&&(await page.evaluate(()=>homeworkTutorUI.inspect().phase))!=='done';i++)await page.getByRole('button',{name:'下一段',exact:true}).click();
  assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'done');assert.equal(await page.evaluate(()=>JSON.stringify(homeworkTutorUI.inspect().evidence)),saved);
  await page.getByRole('button',{name:'试一个同类小判断',exact:true}).click();assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'transfer');
  await page.getByRole('button',{name:'先继续讲',exact:true}).click();assert.equal(await page.evaluate(()=>homeworkTutorUI.inspect().phase),'done');assert.equal(await page.evaluate(()=>JSON.stringify(homeworkTutorUI.inspect().evidence)),saved);
  await shot('05-本次讲题摘要');
  await page.getByRole('button',{name:'返回原题',exact:true}).click();
  assert.equal(await page.locator('.hp-grade-detail').count(),1);
  assert.deepEqual(errors,[]);
  writeFileSync(resolve(output,'result.json'),JSON.stringify({passed:true,errors,scenarios:['direct entry','split board/caption','wait','local help','pause and aside','resume','original preview','summary','return']},null,2));
  console.log('PASS: real browser tutoring entry, wait/help, nested intent, pause, persistence, original preview, summary and return. '+output);
}finally{await browser.close();}
